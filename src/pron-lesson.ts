/** 把 `[bed]` 这种音标剥掉外壳，拿到里面那串音素 */
export const 剥壳 = (ipa: string): string => ipa.replace(/^[[/'’]+/, '').replace(/[\]/]+$/, '');

/**
 * 能不能干净地一个音一个音切开。
 * **只切有把握的**：纯粹由"单字符音素"组成的短词（[bed] → b–e–d）。
 * 带长音符、双元音、连写辅音、重音号、括号的一律**不切**，页面改说"照着音标拼"——
 * 切错一个音比不切伤害大得多（底线 3）。
 */
export function 拆音标(ipa: string): string[] | null {
  const s = 剥壳(ipa);
  if (!s || /[ːˈˌ()（）.\-\s]/.test(s)) return null;
  const 单字符音素 = new Set([
    'b', 'd', 'f', 'g', 'h', 'k', 'l', 'm', 'n', 'p', 'r', 's', 't', 'v', 'w', 'z', 'j',
    'e', 'æ', 'ɪ', 'ʊ', 'ʌ', 'ɒ', 'ə',
  ]);
  const out = [...s];
  if (out.length < 2 || out.length > 5) return null;
  for (const c of out) if (!单字符音素.has(c)) return null;
  return out;
}

