/** 一步指令的出处 */
export type 出处 = '课件原文' | '课程练法' | '机械拆分';

/** 课程 S1 的四级练法（顺序就是课程写的顺序） */
export const 级 = ['单音', '音素拼合', '单词拼读', '句子和绕口令'] as const;
export type 级名 = (typeof 级)[number];

export interface Step {
  /** 第几级（0..3），对应 `级` */
  lv: 0 | 1 | 2 | 3;
  /** 这一步**唯一**要他做的事，一句祈使句 */
  说: string;
  /** 大字显示的那一个东西（音标 / 拼合 / 词）；没有就不显示 */
  大?: string;
  /** 一两句补充，说清楚"做到什么程度算对" */
  提示?: string;
  /** 这一步凭什么这么说（原文 / 练法名） */
  依据: string;
  类: 出处;
  /** 要放的标准音：`src/pron.ts` 的词编号；没有就没有 🔊 */
  音?: string;
  /** 这一步可以让他念、机器听（纠说）；值是词编号 */
  麦?: string;
}

