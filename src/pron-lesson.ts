const 动作 = (s: PronSound): { 原文: string; 说: string; 提示?: string; 看不见?: boolean }[] =>
  s.mouth.map((m) => {
    const a = 动作表[m];
    // 课件写了一条口型，而这里没有对应动作 —— 宁可整条不出，也不编一句（测试守着不许发生）
    return a ? { 原文: m, ...a } : null;
  }).filter((x): x is NonNullable<typeof x> => x !== null);

/** 第 1 级 单音：把一个音的口型定位逐条摊成动作，最后让他发这个音 */
function 单音(g: PronGroup, which: 'a' | 'b', 跳过共同: boolean): Step[] {
  const s = g[which];
  const 另 = g[which === 'a' ? 'b' : 'a'];
  const 共同 = new Set(另.mouth.filter((m) => s.mouth.includes(m)));
  const out: Step[] = [];

  if (跳过共同 && 共同.size) {
    // 第二个音不重复念一遍一样的动作，只提醒"这几样不变"（省掉无谓的重复点击）
    out.push({
      lv: 0,
      说: '这几样和刚才一样，不用改：' + [...共同].join('、') + '。',
      提示: '只有下面这一处要变。',
      依据: '课件原文：两个音的这几条口型定位写的一样',
      类: '课件原文',
    });
  }

  for (const a of 动作(s)) {
    if (跳过共同 && 共同.has(a.原文)) continue;
    out.push({
      lv: 0,
      说: a.说,
      提示: a.提示,
      依据: '课件原文：' + a.原文,
      类: '课件原文',
    });
  }

  // 有没有一条**看得见的**口型动作。第 7 组课件只说了"发音似「日」/「知」"，一条口型都没给 ——
  // 那就不许说"保持这个口型"，没有口型可保持（底线 3）。
  const 有口型 = 动作(s).some((a) => !a.看不见);
  out.push({
    lv: 0,
    说: 有口型 ? '保持这个口型，发这个音。' : '现在发这个音。',
    大: s.ipa,
    提示: 有口型
      ? '课件管它叫「' + s.nick + '」。'
      : '课件对这个音只给了"' + s.mouth.join('、') + '"，没有口型定位 —— 这一组只能靠耳朵和喉咙，没法对着镜子做。',
    依据: '课件原文：' + s.ipa + ' ' + s.nick,
    类: '课件原文',
  });
  return out;
}

/** 第 2 级 音素拼合：辅音 + 元音（课程原例 /p–iː–piː/），用这一组自己的词的首音搭 */
function 拼合(g: PronGroup): Step[] {
  const 头 = (word: string) => word[0].toLowerCase();
  const 第一对 = g.pairs[0];
  const out: Step[] = [];
  ([['a', g.a, 第一对.a], ['b', g.b, 第一对.b]] as const).forEach(([, s, word]) => {
    const c = 头(word.word);
    const 元音组 = g.kind === '元音';
    // 元音组：拿词的首辅音去拼这个元音。辅音组：这个辅音本身就是要练的，拿它拼一个元音。
    const 左 = 元音组 ? c : 剥壳(s.ipa);
    const 右 = 元音组 ? 剥壳(s.ipa) : 'ɑː';
    out.push({
      lv: 1,
      说: '把这两个音分开念，再并成一个。',
      大: 左 + '–' + 右 + ' → ' + 左 + 右,
      提示: '并之前先把口型摆好，摆好了再出声。',
      依据: '课程练法：音素拼合（辅音加元音，课件原例 /p–iː–piː/；这一组的组合是按同一个练法现搭的，不是课件原例）',
      类: '课程练法',
    });
  });
  return out;
}

/** 第 3 级 单词拼读：按音标一个音一个音拼（课程原例 [t–ɪ–p] tip） */
function 拼读(g: PronGroup): Step[] {
  const out: Step[] = [];
  g.pairs.forEach((p, i) => {
    (['a', 'b'] as const).forEach((k) => {
      const word: PronWord = p[k];
      const 拆 = 拆音标(word.ipa);
      const id = wordId(g, i, k);
      out.push({
        lv: 2,
        说: 拆 ? '按音标一个音一个音拼出来，拼完再整个念一遍。' : '照着音标拼出来，一个音一个音来。',
        大: 拆 ? 拆.join('–') + ' → ' + word.word : word.word + ' ' + word.ipa,
        提示: 拆 ? undefined : '这个词的音标里有长音或双元音，拆开反而会拆错，所以照着整串拼。',
        依据: 拆
          ? '课件原文音标 ' + word.ipa + '，按符号切开（课程练法：单词拼读，原例 [t–ɪ–p] tip）'
          : '课件原文词与音标：' + word.word + ' ' + word.ipa,
        类: 拆 ? '机械拆分' : '课件原文',
        音: id,
        麦: word.asr ? id : undefined,
      });
    });
  });
  return out;
}

/**
 * 反向逆读：**逐句**把词序倒过来，句末标点留在句末。
 * 不这么做会出两种笑话：句号跟着最后一个词跑到最前面（`pens. ten Ann…`），
 * 两句话的绕口令（第 7 组）整体倒读会把两句串成一句。
 */
export function 逆读(s: string): string {
  return (s.match(/[^.!?]+[.!?]*/g) ?? [s])
    .map((句) => {
      const m = 句.match(/^(\s*)(.*?)([.!?]*)(\s*)$/);
      if (!m) return 句;
      const 词 = m[2].split(/\s+/).filter(Boolean);
      return m[1] + [...词].reverse().join(' ') + m[3];
    })
    .join(' ')
    .trim();
}

/** 第 4 级 句子和绕口令：三最法 + 反向逆读法（都是课程写明的练法） */
function 绕口令(g: PronGroup): Step[] {
  return [
    {
      lv: 3,
      说: '绕口令。用三最法念：最大声、最清晰、最慢速。',
      大: g.twister,
      提示: '慢到每一个音都摆得到位为止。课程的作业标准是"直到没有任何发音错误"。',
      依据: '课件原文绕口令 + 课程练法：三最法（最大声、最清晰、最慢速）',
      类: '课程练法',
    },
    {
      lv: 3,
      说: '反向逆读法：从最后一个词往前读。',
      大: 逆读(g.twister),
      提示: '这一步专治"看懂了就读快"。倒着读你没法滑过去，每个词的口型都得重新摆。',
      依据: '课程练法：反向逆读法（句子从后往前读，第 5 课起用）',
      类: '课程练法',
    },
  ];
}

/** 一组的完整阶梯 */
export function stepsOf(g: PronGroup): Step[] {
  return [...单音(g, 'a', false), ...单音(g, 'b', true), ...拼合(g), ...拼读(g), ...绕口令(g)];
}

/** 七组的阶梯，页面一次拿走 */
export const LESSON = GROUPS.map((g) => ({
  组: g.id,
  名字: g.a.ipa + ' vs ' + g.b.ipa,
  课: g.lesson,
  步: stepsOf(g),
}));
