/**
 * 发音训练「**口型示意图**」的依据表（Amos 2026-11-11：「有些发音我很难理解　你要给我做成教学视频」——
 * 真人视频拍不了、AI 生成的"会动的嘴"是编的不能做，改成三样：①口型示意图 + 动画 ②前置摄像头当镜子 ③慢速对照 + 录音回放）。
 *
 * **这个文件存在的唯一理由是底线 3（不编造）**：
 *   画面上**每一个可见差别，都必须能指回 `src/pron-content.ts` 里那个音的 `mouth` 数组中的某一条**。
 *   所以图不是画出来的，是**从 `mouth` 的原文逐条翻译出来的** —— 这里只做翻译，`src/pron-page.ts` 按翻译结果画 SVG。
 *   课件没说的（舌位、气流、唇形变化），这里**根本没有字段可以表达**，页面也就画不出来。
 *
 * 规则只有三条：
 *   1. 每条 `mouth` 原文都要有归宿：要么翻成一个**可见特征**（`画了`，带 `依据` 原文），
 *      要么进 `没画`（带"为什么画不出来"）。**一条都不许悄悄丢掉**（test/pron.test.ts 第 10 组逐条核对）。
 *   2. 两个音之间**只有翻译结果不同的地方才画成不同**；课件写的一样的（例如 g1 两个音都是「咧嘴」「舌头平躺抵下齿」），
 *      **必须画成一模一样**。
 *   3. 翻译不出任何可见特征（g7）就**不画图**，页面照实说"课件没给口型"。
 *
 * **逐组实况**（哪几组画得出差别、哪几组画不出，这是跟 Amos 必须说清楚的那件事）：
 *   g1 /e/ vs /æ/     → **画得出**。唯一的差别是上下齿开口：1cm（一根食指）vs 2cm（两根食指）。
 *                        两个都是「咧嘴」「舌头平躺抵下齿」→ 嘴型和舌位**画成一样**。
 *   g2 /eɪ/ vs /iː/   → **画得出**。/eɪ/ 是「上下齿由微张后慢慢闭合」（会动，两帧），/iː/ 是「距离几乎为 0」（不动）。
 *                        两个都是「扁平咧嘴」「舌头平躺抵下齿」。⚠️「微张」课件**没给尺寸**，所以画成虚线、不标厘米、不给手指参照。
 *   g3 /aɪ/ vs /æ/    → **画得出**。/aɪ/ 是「先张嘴后咧嘴」+「上下齿张开后慢慢闭合」（会动），/æ/ 是「咧嘴」+ 固定 2cm。
 *   g4 /f/ vs /v/     → **画不出**。两个都是「上齿轻咬下唇」，**口型一模一样**；差的是「送气不发声」vs「声带振动」，
 *                        嘴外面看不出来 → 页面写明「用手摸喉咙，振动的是 /v/」（摸喉咙这句来自课件「声带振动」）。
 *   g5 /l/ vs /r/     → **画得出，但在嘴里面**。「舌尖轻抵上齿龈」vs「舌尖向上腾空卷起」→ 画**剖面示意**，
 *                        并写明"舌头在嘴里面，镜子里看不到"。课件没给这两个音的唇形 → **一个唇都不画**。
 *   g6 /n/ vs /l/     → **画不出**。两个都是「舌尖轻抵上齿龈」，舌位一样；差的是「气流从鼻腔流出」vs「气流从舌侧流出」，
 *                        而且两个都振动声带 → **摸喉咙也分不出**，页面照实说。
 *   g7 /ʒ/ vs /dʒ/    → **一张图都不画**。课件只给了「发音似「日」」「发音似「知」」+「声带振动」，一句口型都没有。
 *
 * 不碰密钥、不存东西、不调 AI：纯函数，只读 `src/pron-content.ts`。
 */
import type { PronGroup, PronSound } from './pron-content';

/** 画面上能出现的可见特征，就这四个（多一个都没有，因为课件只说了这四类事） */
export type 特征名 = '唇' | '开口' | '手指' | '舌';

/** 一个可见特征：画成什么 + **依据是 `mouth` 里的哪一条原文** */
export interface MouthFeat {
  特征: 特征名;
  /** 画成什么（页面按这个值画 SVG；比较两个音是否相同也比这个值） */
  值: string;
  /** 依据：课件 `mouth` 数组里的那一条**原文**，一个字没改 */
  依据: string;
}

/** 一条看不出口型的（喉咙、气流、"似某个字"）：原样列出来 + 为什么画不出来 */
export interface MouthUnseen {
  原文: string;
  为什么: string;
  /** 归类：振动 / 送气 / 气流 / 似（页面的说明按这个分支措辞） */
  类: '振动' | '送气' | '气流' | '似' | '别的';
}

/** 一个音翻译出来的画法 */
export interface MouthSpec {
  音标: string;
  外号: string;
  /** 正面图（嘴唇 + 上下齿开口）；课件没给唇齿就是 null，页面不画正面 */
  正面: null | {
    唇: 唇型;
    /** 上下齿开口（毫米）。`到毫米` 不为 null = 会动的（由…到…），两帧 */
    开口毫米: number | null;
    到毫米: number | null;
    /** 课件给没给尺寸：没给（「微张」「张开」）就画虚线、不标厘米、不给手指参照 */
    有尺寸: boolean;
    /** 几根食指（课件原文「可容纳一根食指」）；没说就是 null，**不许自己换算** */
    手指: number | null;
  };
  /** 剖面图（舌位）；课件没给舌位就是 null */
  剖面: null | { 舌: '平躺抵下齿' | '舌尖抵上齿龈' | '舌尖卷起' };
  /** 画了哪些可见特征（每条带依据原文） */
  画了: MouthFeat[];
  /** 没画的那几条（喉咙、气流、"似某个字"） */
  没画: MouthUnseen[];
}

/** 一组两个音合起来：差在哪、哪些画成一样、页面上照实说什么 */
export interface MouthPair {
  a: MouthSpec;
  b: MouthSpec;
  /** 这一组的差别画得出来吗（画不出就不许画出一个假的嘴型差别） */
  画得出差别: boolean;
  /** 画面上哪几处不一样（逐条带两边的课件原文） */
  差别: string[];
  /** 哪几处课件写的一样 → 必须画成一样（原文） */
  一样的: string[];
  /** 舌头那张是剖面（在嘴里面，镜子里看不到） */
  有剖面: boolean;
  /** 摸喉咙分得出来吗：一边送气不发声、另一边声带振动才算（两个都振动就分不出，照实说） */
  摸喉咙: boolean;
  /** 页面上那段话（底线 3：画得出就说画了什么，画不出就说为什么画不出） */
  说明: string;
}

