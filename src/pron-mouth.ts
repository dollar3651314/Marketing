/** 唇：课件写的四种说法 */
export type 唇型 = '咧嘴' | '扁平咧嘴' | '先张嘴后咧嘴' | '上齿轻咬下唇';
const 唇表: [string, 唇型][] = [
  // 顺序要紧：「扁平咧嘴」「先张嘴后咧嘴」都含「咧嘴」，长的先匹配
  ['扁平咧嘴', '扁平咧嘴'],
  ['先张嘴后咧嘴', '先张嘴后咧嘴'],
  ['上齿轻咬下唇', '上齿轻咬下唇'],
  ['咧嘴', '咧嘴'],
];

/** 舌：课件写的三种说法 */
const 舌表: [string, '平躺抵下齿' | '舌尖抵上齿龈' | '舌尖卷起'][] = [
  ['舌头平躺抵下齿', '平躺抵下齿'],
  ['舌尖轻抵上齿龈', '舌尖抵上齿龈'],
  ['舌尖向上腾空卷起', '舌尖卷起'],
];

/** 中文数字 → 几根食指（课件只写过「一根」「两根」） */
const 根数: Record<string, number> = { 一: 1, 两: 2 };

/**
 * 上下齿那一条 → 开口几毫米。
 * **只有课件写了数字的才有尺寸**：「1cm 左右」→ 10mm、「2cm 左右」→ 20mm、「几乎为 0」→ 0mm。
 * 「微张」「张开」课件**没给尺寸**，所以 `有尺寸: false` —— 页面画虚线、不标厘米、不给手指参照（不自己编一个数）。
 * 画虚线用的那个高度只是"比闭合大一点"的示意，不代表任何厘米数，这一点页面上也写着。
 */
function 读开口(line: string): { 开口毫米: number; 到毫米: number | null; 有尺寸: boolean } | null {
  if (!line.includes('上下齿')) return null;
  const cm = /([0-9]+(?:\.[0-9]+)?)\s*cm/.exec(line);
  // 「由微张后慢慢闭合」「张开后慢慢闭合」：会动的两帧，起点课件没给尺寸
  if (line.includes('闭合')) {
    const 微 = line.includes('微张');
    return { 开口毫米: 微 ? 4 : 12, 到毫米: 0, 有尺寸: false };
  }
  if (cm) return { 开口毫米: Math.round(Number(cm[1]) * 10), 到毫米: null, 有尺寸: true };
  if (line.includes('几乎为 0') || line.includes('几乎为0')) return { 开口毫米: 0, 到毫米: null, 有尺寸: true };
  return null;
}

/** 看不出口型的那几条：归类 + 为什么画不出来（说法逐条写死，不自由发挥） */
function 读不可见(line: string): MouthUnseen {
  if (line.includes('振动')) return { 原文: line, 类: '振动', 为什么: '声带振不振动在喉咙里，嘴外面看不出来 —— 用手摸喉咙能感觉到。' };
  if (line.includes('送气')) return { 原文: line, 类: '送气', 为什么: '送不送气是气流的事，嘴外面看不出来。' };
  if (line.includes('气流')) return { 原文: line, 类: '气流', 为什么: '气流走鼻腔还是走舌侧，嘴外面看不出来。' };
  if (line.includes('发音似')) return { 原文: line, 类: '似', 为什么: '课件只说了它听起来像哪个中文字，没给口型 —— 没有可以画的东西。' };
  return { 原文: line, 类: '别的', 为什么: '这一条说的不是看得见的口型，画不出来。' };
}

/** 一个音：`mouth` 逐条翻译。**每条原文都有归宿**（要么进 `画了`，要么进 `没画`） */
export function mouthSpec(s: PronSound): MouthSpec {
  const 画了: MouthFeat[] = [];
  const 没画: MouthUnseen[] = [];
  let 正面: MouthSpec['正面'] = null;
  let 剖面: MouthSpec['剖面'] = null;

  for (const line of s.mouth) {
    const 唇 = 唇表.find(([k]) => line.includes(k));
    const 开口 = 读开口(line);
    const 舌 = 舌表.find(([k]) => line.includes(k));
    if (唇) {
      正面 = 正面 ?? { 唇: 唇[1], 开口毫米: null, 到毫米: null, 有尺寸: true, 手指: null };
      正面.唇 = 唇[1];
      画了.push({ 特征: '唇', 值: 唇[1], 依据: line });
      continue;
    }
    if (开口) {
      正面 = 正面 ?? { 唇: '咧嘴', 开口毫米: null, 到毫米: null, 有尺寸: true, 手指: null };
      正面.开口毫米 = 开口.开口毫米;
      正面.到毫米 = 开口.到毫米;
      正面.有尺寸 = 开口.有尺寸;
      画了.push({ 特征: '开口', 值: 开口.到毫米 == null ? String(开口.开口毫米) : `${开口.开口毫米}→${开口.到毫米}`, 依据: line });
      const 指 = /可容纳(.)根食指/.exec(line);
      const n = 指 ? 根数[指[1]] : undefined;
      if (n) {
        正面.手指 = n;
        画了.push({ 特征: '手指', 值: String(n), 依据: line });
      }
      continue;
    }
    if (舌) {
      剖面 = { 舌: 舌[1] };
      画了.push({ 特征: '舌', 值: 舌[1], 依据: line });
      continue;
    }
    没画.push(读不可见(line));
  }
  // 「咧嘴」这类只说了唇、没说上下齿的（g4 的「上齿轻咬下唇」）：开口留 null，页面不画开口线
  return { 音标: s.ipa, 外号: s.nick, 正面, 剖面, 画了, 没画 };
}

/** 这一组两个音的某个特征：同一个值就是"课件写的一样"，不同就是"画面上该不一样的那一处" */
const 取 = (sp: MouthSpec, k: 特征名) => sp.画了.find((f) => f.特征 === k) ?? null;

/** 特征的中文说法（只用来组句子，不影响画面） */
const 特征说法: Record<特征名, string> = { 唇: '嘴唇', 开口: '上下齿的开口', 手指: '食指参照', 舌: '舌头的位置' };

/** 一组：两个音并排，差在哪、哪些必须画成一样、页面上照实说什么 */
export function mouthPair(g: PronGroup): MouthPair {
  const a = mouthSpec(g.a);
  const b = mouthSpec(g.b);
  const keys: 特征名[] = ['唇', '开口', '手指', '舌'];
  const 差别: string[] = [];
  const 一样的: string[] = [];
  for (const k of keys) {
    const fa = 取(a, k);
    const fb = 取(b, k);
    if (!fa && !fb) continue;
    // 手指参照跟着开口走：开口一样时它也一样，不单独算一处差别
    if (fa && fb && fa.值 === fb.值) {
      一样的.push(fa.依据);
      continue;
    }
    if (k === '手指') continue;
    差别.push(`${特征说法[k]}：${g.a.ipa} 是「${fa ? fa.依据 : '课件没说'}」，${g.b.ipa} 是「${fb ? fb.依据 : '课件没说'}」`);
  }
  const 有剖面 = !!(a.剖面 || b.剖面);
  const 画得出差别 = 差别.length > 0;
  const 没口型 = !a.正面 && !b.正面 && !a.剖面 && !b.剖面;
  // 看不出口型的那几条，哪几条两边**真的不一样**：
  // 「振动声带」和「声带振动」是课件换了个说法、说的是同一件事，所以按「类」比，不按字面比；
  // 气流、"似某个字"按原文比（鼻腔 vs 舌侧、似「日」vs 似「知」是真的不一样）。
  const 键 = (x: MouthUnseen) => (x.类 === '振动' ? '振动' : x.原文);
  const kb0 = new Set(b.没画.map(键));
  const ka0 = new Set(a.没画.map(键));
  const 只有a = a.没画.filter((x) => !kb0.has(键(x)));
  const 只有b = b.没画.filter((x) => !ka0.has(键(x)));
  const 两边都有 = a.没画.filter((x) => kb0.has(键(x)));
  // 摸喉咙分得出来 = 一边「送气不发声」、另一边「声带振动」（两个都振动就分不出，照实说）
  const 类 = (s: MouthSpec) => new Set(s.没画.map((x) => x.类));
  const ka = 类(a);
  const kb = 类(b);
  const 摸喉咙 = (ka.has('送气') && kb.has('振动')) || (kb.has('送气') && ka.has('振动'));
  const 振动的那个 = ka.has('送气') && kb.has('振动') ? g.b.ipa : g.a.ipa;
  const 看不见的差别 =
    只有a.length || 只有b.length
      ? `${g.a.ipa} 是「${只有a.map((x) => x.原文).join('、') || '课件没说'}」，${g.b.ipa} 是「${只有b.map((x) => x.原文).join('、') || '课件没说'}」`
      : '';

  let 说明: string;
  if (画得出差别) {
    说明 = `这两张图不一样的只有 —— ${差别.join('；')}。`;
    if (一样的.length) 说明 += `其余课件写的一样（${[...new Set(一样的)].join('、')}），所以画成一模一样。`;
    if (有剖面) 说明 += '舌头那张是剖面示意 —— 它在嘴里面，镜子里看不到。';
    const 没尺寸的 = [a, b].find((s) => s.正面 && s.正面.开口毫米 != null && !s.正面.有尺寸);
    const 那一条 = 没尺寸的 ? (没尺寸的.画了.find((f) => f.特征 === '开口')?.依据 ?? '') : '';
    if (那一条) 说明 += `虚线那张是因为课件只说了「${那一条}」、没给厘米数 —— 所以不标尺寸、也不给食指参照（不自己编一个数）。`;
    if (看不见的差别) 说明 += `另外还差一件图上画不出来的：${看不见的差别}，那在喉咙 / 气流里，嘴外面看不见。`;
  } else if (没口型) {
    说明 =
      `课件给这两个音的只有：${g.a.ipa} ${a.没画.map((x) => x.原文).join('、')}；${g.b.ipa} ${b.没画.map((x) => x.原文).join('、')}。` +
      '一句口型都没有 —— 所以这一组一张图都不画，不给你编一个假的嘴型差别。' +
      '课件只说了它们听起来像哪个中文字，那是耳朵的事，不是嘴型的事。';
  } else {
    说明 = `这两个音的${有剖面 && !a.正面 ? '舌位' : '口型'}课件写的一模一样（${[...new Set(一样的)].join('、')}），画出来只能是同一张图。`;
    说明 += 看不见的差别 ? `差别是：${看不见的差别} —— 嘴外面看不出来。` : '差别在嘴外面看不出来。';
    说明 += 摸喉咙
      ? `用手摸喉咙：振动的是 ${振动的那个}。`
      : `${两边都有.some((x) => x.类 === '振动') ? '两个都振动声带，摸喉咙也分不出来' : '摸喉咙也分不出来'} —— 课件说的差别是气流走哪里，没有任何外部动作看得见。`;
  }
  return { a, b, 画得出差别, 差别, 一样的: [...new Set(一样的)], 有剖面, 摸喉咙, 说明 };
}
