-- 工作台「带练」的**发音**（服务端 src/drill-audio.ts，页面 src/drill-page.ts）。
--
-- 为什么要存字节（和语音生成工具 src/tts.ts 的"不落库"正相反）：
--   Amos 2026-11-09 原话「不只是加音标 还得有发音 让我可以照着学」。带练的 24 段发音是**固定内容**
--   （18 项 + 第三段 6 句"对方说的那句"），每次打开都重新生成就是每次都花钱、还每次都有失败的可能。
--   **第一次需要时生成一次，之后永久复用**：一共约 20 neurons（melotts 单句约 0.8），免费额度 10,000/天，
--   不新增任何付费服务（底线 8 / C117）。语音生成工具是"随便给一段文字"，这里是"固定的 24 段"，所以一个存、一个不存。
--
-- item 的编号：w1..w6 / p1..p6 / s1..s6 是那一项要说的英文，**另加 s1p..s6p = 第三段「对方说的那句」**（p = prompt）。
-- 只 CREATE，不 ALTER、不 DROP、不加索引、不回填（旧表一行不动）。主键就是编号，最多 24 行，不需要索引。
-- **不存任何密钥**（底线 1）：melotts 走 env.AI 绑定，不用密钥；这张表里只有编号、MP3 字节和时间。

CREATE TABLE drill_audio (
  item TEXT PRIMARY KEY,      -- 项目编号 w1..s6，另加 s1p..s6p 表示第三段「对方说的那句」
  mp3 BLOB NOT NULL,
  at INTEGER NOT NULL
);
