-- 工作台「带练」的**复考**（服务端 src/drill-review.ts，页面 src/drill-page.ts）。
--
-- 为什么有这一张：Amos 2026-11-09 原话「做完后不知道该干什么」。18 项走完以后，小结页给一个大按钮
-- 「明天再考我这 18 项」——按下去就在这里记一笔"明天同一时刻到期"；到期后再打开带练，三段合成一轮、
-- 顺序打散、**只考不给提示**，最后报"说得出来 N / 18"。
--
-- **不动 0013**：复考不改 drill_item 的进度（他哪一项是第几次会的，那是学的记录，复考不该把它刷掉）。
-- 一轮复考**中途的进度不存**（18 项一口气走完，中途刷新就从头考）——所以这里只有三列：
--   scene   场景号（这一版只有场景 0，一个场景只排一次复考，所以直接当主键）
--   due_at  什么时候到期（毫秒时间戳；没到期页面写"下次复考：X 月 X 日"，可以提前开始）
--   mode    复考的方式（这一版只有"只考"：不给关键点、不给词意，只记对错）
--
-- 只 CREATE，不 ALTER、不 DROP、不加索引、不回填（旧表一行不动）。**不存任何密钥**（底线 1）。

CREATE TABLE drill_review (
  scene INTEGER PRIMARY KEY,
  due_at INTEGER NOT NULL,
  mode TEXT NOT NULL
);
