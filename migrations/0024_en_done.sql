-- 「发音训练」的**待办清单**：哪几件事已经打上勾了（页面 src/pron-page.ts 的第 0 屏，服务端 src/pron.ts）。
--
-- 为什么有这一张（Amos 2026-11-13 原话）：
--   「学习进度模块 **将我要做的事情 做成一个 checklist 让我照着做 并在完成后一个一个的勾选确认**」
--   「发音训练 不是要改成 发音的待办事项吗？」
-- 他选的是 A 方案：七组，每组四条（跟我做 N 步走完 / 对照听过 / 考 10 题过关 / 用 🎤 把这一组念过一遍），
-- **点一条才进去做那件事，做完回来自动打上勾**。
--
-- **为什么非要新加一张表**：在这之前，库里**一条"他练到哪了"的记录都没有** ——
-- `pron_round` 只记每一轮的成绩，`pron_say` 只记每一次纠说，
-- 「跟我做走完了没有」「对照听过没有」**没有任何地方记**。清单要能打勾，就必须有地方记。
--
-- **只记两条**：`follow`（跟我做走完）和 `listen`（对照听过）。
-- 另外两条（`quiz` 考 10 题过关 / `say` 这一组的词都念过一遍）是**按现成的成绩算出来的**
-- （`pron_round.passed` / `pron_say.target`），**不写进这张表** —— 同一件事有两个真相是底线 3 的反面。
-- 算出来的那两条也因此**没法取消**，页面上照实写明「按你的成绩算的」。
--
-- **取消就删那一行**。机器勾的那一下**只在"那件事刚发生"的那一刻写一次**，不是每次打开都重算 ——
-- 所以他取消掉的那一条，下次打开**不会被自动勾回来**（他想重做就自己再走一遍）。
--
-- **只 CREATE**：旧表一张都不 DROP、不 ALTER（`pron_round` / `pron_say` / `pron_audio` / `en_audio` /
-- `en_audio_part` / `drill_*` / `ear_pair` 一行都没动，他的历史成绩还在）。
-- **不存任何密钥**（底线 1）：这里只有任务键、时间和一个 auto / me。
--
-- k   ：任务键 `s1:<组>:<任务>`，例如 s1:g1:follow / s1:g1:listen（`src/pron.ts` 的 任务键()）。
--       前缀 `s1:` 是课程 S1（发音训练）；句子训练 S2 的清单是下一批，到时候用 `s2:` 开头，这张表照样装得下。
-- at  ：勾上的时间。
-- by  ：'auto'（机器在那件事发生的那一刻记的）还是 'me'（他自己点的）。

CREATE TABLE en_done (
  k  TEXT    NOT NULL PRIMARY KEY,
  at INTEGER NOT NULL,
  by TEXT    NOT NULL
);
